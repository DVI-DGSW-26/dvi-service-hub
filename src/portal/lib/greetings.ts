/** 요일에 맞춰 섞어 넣는 문구 (일=0 … 토=6) */
const BY_DAY: Record<number, string[]> = {
  0: ['주말에도 수고 많아요', '{name}, 주말 출근 고마워요'],
  1: ['{name}, 힘찬 한 주 시작해요', '월요일도 반가워요', '새로운 한 주예요'],
  2: ['화요일도 힘내요'],
  3: ['한 주의 반이 지났어요'],
  4: ['주말까지 이틀 남았어요'],
  5: ['즐거운 금요일이에요', '{name}, 한 주 수고했어요', '{name}, 주말이 코앞이에요', '금요일, 조금만 더 힘내요'],
  6: ['주말에도 수고 많아요', '{name}, 주말 출근 고마워요'],
}

/** 지금 시간대 · 요일에 어울리는 문구 전부 */
export function greetings(now: Date, name: string): string[] {
  const h = now.getHours()
  const lines = [...(BY_TIME.find((t) => h < t.until) ?? BY_TIME[0]).lines, ...(BY_DAY[now.getDay()] ?? [])]
  const who = `${name} 님`
  return lines.map((l) => (l.includes('{name}') ? l.replace('{name}', who) : `${l}, ${who}`))
}

/** 이름을 아직 모를 때 쓰는 기본 인사 */
export function plainGreeting(now: Date) {
  const h = now.getHours()
  if (h < 5) return '늦은 시간까지 수고 많으세요'
  if (h < 12) return '좋은 아침이에요'
  if (h < 18) return '좋은 오후예요'
  return '좋은 저녁이에요'
}
